// Shadow windows (the skill's kind:'shadow' context): create / list /
// openTab / ping / close, the rebind + incognito-mismatch rules, and that a
// shadow never shows up as an agent pip.
import { openControl, sleep, cdpHttp } from './phi-test.mjs'
const ctl = await openControl()
const show = (l, v) => console.log(l, JSON.stringify(v))
const r = await ctl.send('agentSpace.shadow.create', { taskId: 'sv-shadow-1', profileId: '', incognito: false })
show('create:', r)
show('list:', await ctl.send('agentSpace.shadow.list', {}))
show('openTab:', await ctl.send('agentSpace.shadow.openTab', { taskId: 'sv-shadow-1', url: 'https://example.com/?shadow' }))
await sleep(2000)
const targets = await cdpHttp('/json/list')
const mine = targets.filter(t => t.type === 'page' && /shadow/.test(t.url))
console.log('page targets in shadow:', mine.length, mine.map(t => t.url))
const l = await ctl.send('agentSpace.list', {})
console.log('agent tasks (should not include shadow):', JSON.stringify(l.tasks), 'transcriptMirror:', l.transcriptMirror, 'windows has shadow:', (l.windows || []).includes(r.windowId))
const r2 = await ctl.send('agentSpace.shadow.create', { taskId: 'sv-shadow-1', incognito: false })
console.log('rebind same window:', r2.windowId === r.windowId, JSON.stringify(r2))
show('incognito mismatch (refused):', await ctl.send('agentSpace.shadow.create', { taskId: 'sv-shadow-1', incognito: true }))
show('ping:', await ctl.send('agentSpace.shadow.ping', { taskId: 'sv-shadow-1', ttlSeconds: 60 }))
show('tabGroups.list scoped to shadow task:', await ctl.send('agentSpace.tabGroups.list', { taskId: 'sv-shadow-1' }))
const inc = await ctl.send('agentSpace.shadow.create', { taskId: 'sv-shadow-inc', incognito: true })
show('incognito create:', inc)
show('incognito openTab:', await ctl.send('agentSpace.shadow.openTab', { taskId: 'sv-shadow-inc', url: 'https://example.com/?incognito' }))
await sleep(2000)
show('list2:', await ctl.send('agentSpace.shadow.list', {}))
show('close 1:', await ctl.send('agentSpace.shadow.close', { taskId: 'sv-shadow-1' }))
show('close inc:', await ctl.send('agentSpace.shadow.close', { taskId: 'sv-shadow-inc' }))
await sleep(1200)
show('list after close:', await ctl.send('agentSpace.shadow.list', {}))
show('ping after close (unknown_task):', await ctl.send('agentSpace.shadow.ping', { taskId: 'sv-shadow-1' }))
show('windows now:', (await ctl.send('agentSpace.list', {})).windows)
ctl.close()
